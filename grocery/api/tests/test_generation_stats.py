def test_scenario_relations_have_no_seeder():
    """`control.active_scenarios` and `control.scenario_schedules` are written only by
    the POST routes. Nothing seeds them, so they are 0 rows on every slot until someone
    calls them by hand — the calendar regimes (labour day, thanksgiving, …) come from
    `scenario_engine._get_holiday_multiplier`, a pure function of the date that touches
    neither table. `idx_scenario_schedules_dates` exists for the read in
    `get_active_scenario_names`, not as evidence of seeding.

    This test pins the *answer* to the card's question so a future "the schedules table
    is empty, let me add a seeder" is a deliberate change rather than a silent one.
    """
    for path in (REPO_ROOT / "grocery" / "generator" / "main.py",
                 REPO_ROOT / "grocery" / "generator" / "scenarios" / "scenario_engine.py"):
        assert not re.search(r"INSERT INTO control\.(active_scenarios|scenario_schedules)",
                             path.read_text()), (
            f"{path.name} now seeds control.active_scenarios / scenario_schedules; "
            "update the API route docs, which state they are manual-only"
        )

    # The only writers left must be the two POST route pairs (one per industry), and each
    # writes its own relation once.
    api = (REPO_ROOT / "base" / "api" / "main.py").read_text()
    writers = re.findall(
        r"INSERT INTO control\.(active_scenarios|scenario_schedules)\b", api)
    assert sorted(writers) == ["active_scenarios", "active_scenarios",
                               "scenario_schedules", "scenario_schedules"], (
        f"unexpected writers of the scenario relations in base/api/main.py: {writers}"
    )
