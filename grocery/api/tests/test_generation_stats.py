def test_route_is_paginated_on_a_total_order():
    """A page is only complete if the ORDER BY is a total order.

    `recorded_at` alone is not one: a 30 s tick and the backfill's per-hour rows can
    share a stamp, and a tie cluster straddling a page boundary is returned twice or
    never while `total` still matches — the exact failure class that cost data-lab 272
    `online.order_events` rows (t_d7892e10, t_7c88f2f9).
    """
    body = _route_source()
    assert "OFFSET %s" in body, "the stats route does not paginate"
    order_by = re.findall(r"ORDER BY ([^\n]+)", body)
    assert order_by, "the stats route paginates without an ORDER BY"
    for clause in order_by:
        keys = [part.strip() for part in clause.split(",")]
        last = re.split(r"\s+", keys[-1])[0].split(".")[-1]
        assert last == "stat_id", (
            f"the stats route paginates on {clause!r}; a page must end on the primary "
            "key (stat_id) or tied rows can be double-counted or lost"
        )


def test_route_takes_a_limit_larger_than_the_old_ticks_cap():
    """The old `le=1000` on `last_n_ticks` was the ceiling on the whole relation.

    Both page-size parameters have to be raised above it, since a caller can reach the
    route with either. The annotation is matched loosely (`int` or `Optional[int]`) so
    this pins the *cap*, not the spelling.
    """
    body = _route_source()
    caps = {}
    for name in ("limit", "last_n_ticks"):
        match = re.search(rf"{name}:\s*(?:Optional\[)?int\]?\s*=\s*Query\([^)]*le=(\d+)\)", body)
        assert match, f"the stats route declares no capped {name}"
        caps[name] = int(match.group(1))
    for name, cap in caps.items():
        assert cap > 1000, (
            f"{name} is still capped at {cap}: the relation holds tens of thousands of "
            "rows and a consumer that cannot page is a bounded mirror"
        )


def test_route_window_covers_the_business_clock():
    """`simulation_dt` is business time — when the tick simulated, which a backfill
    backdates. It is what a consumer windows on when asking "what did the generator
    produce for this hour?"."""
    body = _route_source()
    for param in ("start_dt", "end_dt"):
        assert re.search(rf"^\s+{param}: Optional\[datetime\] = None,$", body, re.M), \
            f"the stats route does not declare an optional {param}"
    assert 'filters.append("simulation_dt >= %s"); params.append(start_dt)' in body, \
        "start_dt does not filter simulation_dt"
    assert 'filters.append("simulation_dt <= %s"); params.append(end_dt)' in body, \
        "end_dt does not filter simulation_dt"


def test_route_window_covers_the_insert_clock():
    """`recorded_at` is `DEFAULT NOW()`, written by the same statement as the row, so it
    is monotone and immutable — the only clock a delta load can watermark on.

    This matters here precisely because the backfill backdates: before the backfill
    wrote ledger rows (t_ac80c514) `simulation_dt` was fine for realtime ticks, but a
    backfilled day would sit below the watermark and become unreachable. With both
    windows the two families are read with the clock that suits them.
    """
    body = _route_source()
    for param in ("created_after", "created_before"):
        assert re.search(rf"^\s+{param}: Optional\[datetime\] = None,$", body, re.M), \
            f"the stats route does not declare an optional {param}"
    assert 'filters.append("recorded_at >= %s"); params.append(created_after)' in body, \
        "created_after does not filter recorded_at"
    assert 'filters.append("recorded_at <= %s"); params.append(created_before)' in body, \
        "created_before does not filter recorded_at"


def test_route_shares_one_where_clause_between_count_and_page():
    """A filter applied to the page but not the count (or the reverse) makes `total`
    disagree with the pages — which is the only number a consumer has to check."""
    body = _route_source()
    uses = body.count("WHERE {where}")
    assert uses >= 2, (
        f"the count query and the page query must share one WHERE clause "
        f"(found {uses} uses of `WHERE {{where}}`)"
    )


def test_route_returns_the_pagination_envelope():
    """The route returned a bare JSON list, so a consumer had no total to page against —
    it could only count what it had already read. Every other paginated route here
    returns `{data, total, limit, offset}`.

    The echoed page size is matched by shape, not by the variable name: whether the route
    returns `limit` or the resolved `page_size` is an implementation choice, but the
    envelope's four keys and its agreement with the size actually applied are the
    contract.
    """
    body = _route_source()
    envelope = re.search(
        r'return \{"data": rows, "total": total, "limit": (\w+), "offset": (\w+)\}', body)
    assert envelope, "the stats route does not return the pagination envelope"
    page_size_var = envelope.group(1)
    assert re.search(
        rf"SELECT COUNT\(\*\) AS n FROM control\.generation_stats WHERE \{{where\}}",
        body), "the stats route does not count the rows it is about to serve"
    # The echoed page size must be the one that reached the query, not a dead parameter.
    assert re.search(rf"params \+ \[{page_size_var}, {envelope.group(2)}\]", body), (
        f"the route echoes {page_size_var} but does not apply it to the page query"
    )


def test_last_n_ticks_still_works_and_no_longer_caps_the_route():
    """`last_n_ticks` is the existing consumer's parameter (the UI dashboard reads it at
    `last_n_ticks=200`, and data-lab's readiness sensor has read it), so it must keep
    answering — as a page size, not as the ceiling on the relation."""
    body = _route_source()
    assert re.search(r"last_n_ticks: Optional\[int\] = Query\(None, le=\d+\)", body), \
        "last_n_ticks is gone, or is no longer optional — an existing reader would 422"
    # It has to feed the page size rather than sit unused. `limit` is the variable in
    # that expression and `page_size` the result, so both must appear in the resolution.
    resolution = re.search(r"page_size = (.*)", body)
    assert resolution, "the route never resolves a page size"
    assert "last_n_ticks" in resolution.group(1), (
        "last_n_ticks does not reach the page size — the parameter is accepted and "
        "then ignored, which looks like it worked"
    )
    assert "limit" in resolution.group(1), (
        "the page size ignores limit, so a caller cannot page the route at all"
    )


def test_ambiguous_limit_and_last_n_ticks_is_rejected_not_guessed():
    """Two page sizes at once must not be resolved silently — FastAPI would otherwise
    pick one and the caller could not tell which, which is how a mirror ends up short.

    Matched whitespace-insensitively: the raise may wrap the status code onto its own
    line, and the point is that a 400 exists, not how it is formatted.
    """
    body = _route_source()
    assert re.search(r"HTTPException\(\s*400", body), (
        "the stats route must reject a request that carries both limit and last_n_ticks "
        "with different values, rather than silently preferring one"
    )


@pytest.mark.usefixtures("ensure_api_reachable")
def test_route_answers_a_window_alone(quiesced_generator):
    """Neither window is required: a consumer asking only for the insert clock must get
    an answer, not a 422 — the failure that kept `/grocery/pos/transactions` a full reload
    until t_6d2ebc52."""
    client = quiesced_generator
    only_clock = client.get("/grocery/stats/generation",
                            params={"limit": 1, "created_after": FAR_PAST,
                                    "created_before": FAR_FUTURE})
    assert only_clock.status_code == 200, (
        f"an insert-clock-only window was rejected: {only_clock.status_code} "
        f"{only_clock.text[:200]}"
    )
    unfiltered = client.get("/grocery/stats/generation", params={"limit": 1}).json()
    assert only_clock.json()["total"] == unfiltered["total"] >= 1, (
        "the wide insert window and no window disagree on the row count"
    )


@pytest.mark.usefixtures("ensure_api_reachable")
def test_empty_window_is_empty_in_total_and_in_data(quiesced_generator):
    """A window that cannot contain anything has to say so in `total` too, or the count
    and the pages disagree and a consumer's completeness check passes on a hole."""
    client = quiesced_generator
    for params in ({"created_after": FAR_FUTURE}, {"start_dt": FAR_FUTURE}):
        body = client.get("/grocery/stats/generation",
                          params=dict(params, limit=1000)).json()
        assert body["total"] == 0, f"{params} matched rows: total={body['total']}"
        assert body["data"] == [], f"{params} returned rows"


@pytest.mark.usefixtures("ensure_api_reachable")
def test_last_n_ticks_is_honoured_and_offset_pages_through_it(quiesced_generator):
    """The old parameter must still mean "the newest N", and paging has to be able to
    walk past that N — which is the whole point of the change."""
    client = quiesced_generator
    body = client.get("/grocery/stats/generation",
                      params={"last_n_ticks": 5}).json()
    assert body["limit"] == 5, f"last_n_ticks was ignored: limit={body['limit']}"
    assert len(body["data"]) <= 5

    newest = [row["stat_id"] for row in body["data"]]
    if len(newest) < 2:
        pytest.skip("fewer than two ledger rows to page through")
    older = client.get("/grocery/stats/generation",
                       params={"limit": 5, "offset": len(newest)}).json()["data"]
    page_ids = {row["stat_id"] for row in older}
    assert not (page_ids & set(newest)), (
        f"offset={len(newest)} re-returned rows from the first page: a page boundary "
        "inside a tie cluster duplicates and drops rows"
    )


