"""`/{industry}/stats/generation` — the tick ledger has to be readable (t_ac80c514).

Two independent defects, and the second one is the one that made the data *wrong*
rather than merely unreachable.

1. Unreachable. The route took `last_n_ticks` capped at 1000 with no offset and no
   time window, so the newest-1000 slice was all it could ever serve — measured on the
   dev slot: `last_n_ticks=100` → 100 rows, `=1000` → 1000, `=2000` → HTTP 422, against
   a relation holding ~37k rows. A consumer asking "was the generator running while my
   sales dipped?" could not page to the window it cared about, and a bounded mirror was
   the only design left to it.

2. Incomplete. The ledger has two clocks and a scenario tag, and the *backfill* wrote
   none of it. `run_backfill` — the path that writes every day of a fresh install, and
   every day a gap-fill repairs — never called `record_stats`, so days generated by a
   backfill left no ledger row at all. Measured on dev: `control.generation_stats` starts
   at 2026-09-21 (the first realtime tick) while `pos.transactions` starts 2026-08-22 —
   94,867 transactions across 30 days with zero ledger rows. That is why
   `control.generation_stats` holds 0 rows for 2026-09-05..09-09, the labour-day window:
   not a missing scenario *tag*, but no row to carry one. The holiday regime is stamped
   on the transactions and the orders, so a consumer joining the ledger to explain a dip
   found nothing for exactly the days that need explaining, and read a holiday as an
   unexplained anomaly.

   The gas-station and support backfills both write a stat row per simulated hour
   (`gas-station/generator/main.py`, `support/generator/main.py`); grocery was the odd
   one out, and its own tick loop documents `record_stats()` as a lifecycle phase.

So the guards here are:

* the route is windowed and paged on a PK-terminated order, over **both** clocks — the
  table has `simulation_dt` (business time: the hour the tick simulated) and
  `recorded_at` (insert clock), which is exactly the `start_dt`/`end_dt` +
  `created_after`/`created_before` pairing every other backdated route here uses;
* `last_n_ticks` keeps working (it is the existing UI/readiness consumer's parameter)
  but no longer caps what the route can serve;
* the response is the `{data, total, limit, offset}` envelope every other paginated
  route returns, so `total` can describe a window instead of a bare list;
* the backfill writes a ledger row per simulated hour, stamped with the scenario the
  hour's transactions were generated under — which is the same `ScenarioContext` object
  the hour's rows were written from, so the tag cannot drift from the data.
"""
import pathlib
import re

import pytest

REPO_ROOT = pathlib.Path(__file__).resolve().parents[3]
API_SOURCE = REPO_ROOT / "base" / "api" / "main.py"
GENERATOR_MAIN = REPO_ROOT / "grocery" / "generator" / "main.py"

ROUTE_SOURCE_PATH = "/{industry}/stats/generation"
FAR_PAST = "2000-01-01T00:00:00+00:00"
FAR_FUTURE = "2999-01-01T00:00:00+00:00"


def _route_source() -> str:
    """The source of the stats route, from its decorator to the next one."""
    source = API_SOURCE.read_text()
    marker = f'@app.get("{ROUTE_SOURCE_PATH}",'
    start = source.index(marker)
    end = source.index("\n@app.", start + len(marker))
    return source[start:end]


def _backfill_source() -> str:
    """The body of `run_backfill` in the grocery generator."""
    source = GENERATOR_MAIN.read_text()
    start = source.index("def run_backfill")
    return source[start:source.index("\ndef ", start + 10)]


def _backfill_record_stats_call() -> str:
    """The backfill's ledger write — the `record_stats(...)` call.

    Narrower than the hour loop on purpose: the loop already passes `scenario.scenario_tag`
    to `inventory.flush_sales`, so a test that searched the whole loop would report the
    ledger row as tagged when the row itself is untagged.
    """
    backfill = _backfill_source()
    start = backfill.index("record_stats(")
    end = backfill.index(")", backfill.index("sim_dt", start))
    return backfill[start:end + 1]


