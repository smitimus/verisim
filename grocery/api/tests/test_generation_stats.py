def test_backfill_records_a_ledger_row():
    """The defect: `run_backfill` never called `record_stats`, so every day written by a
    backfill — the 30-day window of a fresh install, and every day a gap-fill repairs —
    left no telemetry. A consumer asking whether the generator was up during a dip found
    the answer only for realtime ticks."""
    backfill = _backfill_source()
    assert "generation_stats" in GENERATOR_MAIN.read_text() and \
        "record_stats(" in backfill, (
        "run_backfill writes no control.generation_stats row: a backfilled day is "
        "invisible in the tick ledger, which is how 30 days of transactions came to "
        "exist with no telemetry explaining them (t_ac80c514)"
    )
    # The hourly loop is where the tick's own counts and scenario are known.
    hour_loop = backfill[backfill.index("for hour in range("):]
    assert "record_stats(" in hour_loop, (
        "the backfill writes no ledger row per simulated hour; a per-day aggregate would "
        "lose the hourly resolution the realtime path records every tick"
    )


def test_backfill_stamps_the_scenario_the_hour_ran_under():
    """The tag on the ledger row has to be the one the hour's transactions were written
    with — `scenario.scenario_tag`, the same object the hour's `generate_pos_transactions`
    received. A tag recomputed at write time could disagree with the rows it describes,
    which is the failure the card reports: a holiday regime in the fact tables and
    nothing in the ledger.

    Scoped to the INSERT itself: `scenario.scenario_tag` also appears on the hour's
    `inventory.flush_sales` call, so searching the whole loop would pass on the ledger
    row being untagged.
    """
    call = _backfill_record_stats_call()
    assert "scenario.scenario_tag" in call, (
        "the backfilled ledger row must be stamped with the hour's own "
        "`scenario.scenario_tag` — the context its transactions were generated under"
    )


def test_backfill_records_the_counts_it_actually_wrote():
    """The ledger exists to answer "did the generator run, and how much did it make?".
    Recording the *planned* volume instead of the rows written would make a tick that
    wrote nothing look like a busy one — and a stockout-capped tick (t_959cd040) writes
    strictly fewer rows than it planned."""
    call = _backfill_record_stats_call()
    assert "len(depletion)" in call, (
        "the backfilled ledger row must record the POS rows actually written "
        "(len(depletion)), not the planned `pos_count`"
    )
    assert not re.search(r"\bpos_count\b", call), (
        "the backfilled ledger row records the planned pos_count rather than the rows "
        "written; a stockout-capped or fully-sold-out hour would read as a busy tick"
    )
    assert "len(online_depletion)" in call, (
        "the backfilled ledger row must record the online rows actually written; the "
        "realtime path records `orders_generated`, so a backfilled hour would read as "
        "if the online channel had produced nothing"
    )


def test_backfill_ledger_row_is_written_in_the_hours_transaction():
    """A ledger row is evidence about the tick, so it must be written inside the hour's
    own loop — after that hour's rows, and before the day commits. Written after the
    hourly loop a crash would leave the day's data on disk with no ledger; written in a
    later day's batch, the ledger would describe ticks whose rows had rolled back."""
    backfill = _backfill_source()
    call_at = backfill.index("record_stats(")
    hour_loop_start = backfill.index("for hour in range(")
    day_end = backfill.index("\n        if not is_partial:")
    assert hour_loop_start < call_at < day_end, (
        "the ledger row is not written inside the hourly loop: a day's rows could commit "
        "and the ledger row not, leaving telemetry for data that was rolled back"
    )


def test_backfill_does_not_bump_the_state_clock():
    """`last_tick_at` is what `/status` and data-lab's readiness sensor read as "the
    generator is alive". During a backfill the generator is simulating the past, so
    stamping the wall clock there would make a backfilled hour look like live progress
    and `last_tick_at` would stop being comparable with the ledger's own `recorded_at`.
    """
    call = _backfill_record_stats_call()
    assert "bump_state_clock=False" in call, (
        "run_backfill must pass bump_state_clock=False: stamping last_tick_at while "
        "backfilling history makes the readiness sensor read a generator that is "
        "simulating yesterday as one that is alive (t_ac80c514)"
    )


def test_record_stats_is_reachable_from_both_generation_paths():
    """The docstring at the top of the generator lists `record_stats()` as a lifecycle
    phase of `run_tick`. The backfill is the other path that produces rows a consumer
    will later ask about, so it has to reach the same writer rather than open-coding a
    second INSERT that can drift from the first (as gas-station and support's inline
    INSERTs can)."""
    source = GENERATOR_MAIN.read_text()
    assert source.count("def record_stats") == 1, "more than one record_stats writer"
    start = source.index("def run_backfill")
    backfill = source[start:source.index("\ndef ", start + 10)]
    assert "record_stats(" in backfill, (
        "run_backfill writes its own INSERT instead of calling record_stats: the two "
        "writers will drift, and record_stats also bumps the state clock that the "
        "readiness sensor reads"
    )


